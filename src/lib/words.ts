function shuffle<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export interface WordOptions {
  punctuation?: boolean;
  numbers?: boolean;
  capitals?: boolean;
  longWords?: boolean;
  onlyNumbers?: boolean;
  onlySymbols?: boolean;
}

function randomDigits(): string {
  const len = 2 + Math.floor(Math.random() * 3); // 2-4 digits
  let out = "";
  for (let i = 0; i < len; i++) {
    out += Math.floor(Math.random() * 10);
  }
  return out;
}

function randomSymbols(): string {
  const len = 4 + Math.floor(Math.random() * 4); // 4-7 symbols
  let out = "";
  for (let i = 0; i < len; i++) {
    out += SYMBOLS[Math.floor(Math.random() * SYMBOLS.length)];
  }
  return out;
}

function maybeCapitalize(word: string, useCapitals: boolean): string {
  if (useCapitals && Math.random() < 0.15 && word[0]) {
    return word[0].toUpperCase() + word.slice(1);
  }
  return word;
}

export function generateWords(
  count: number,
  options: WordOptions = {}
): string[] {
  const {
    punctuation = false,
    numbers = false,
    capitals = false,
    longWords = false,
    onlyNumbers = false,
    onlySymbols = false,
  } = options;

  const pool = shuffle(longWords ? LONG_WORDS : COMMON_WORDS);
  const result: string[] = [];
  let last = "";

  const pickWord = (): string => {
    for (let i = 0; i < pool.length + 5; i++) {
      const w = pool[Math.floor(Math.random() * pool.length)];
      if (w !== last) return w;
    }
    return pool[Math.floor(Math.random() * pool.length)];
  };

  for (let i = 0; i < count; i++) {
    let word: string;

    if (onlySymbols) {
      word = randomSymbols();
    } else if (onlyNumbers) {
      word = randomDigits();
    } else if (numbers && Math.random() < 0.12) {
      word = randomDigits();
    } else {
      word = maybeCapitalize(pickWord(), capitals);
      if (punctuation && Math.random() < 0.22) {
        word += PUNCTUATION[Math.floor(Math.random() * PUNCTUATION.length)];
      }
    }

    result.push(word);
    last = word;
  }

  return result;
}
